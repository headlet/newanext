
"use client";

import {
  useRef,
  useState,
  type ChangeEvent,
  type DragEvent,
  type KeyboardEvent,
} from "react";

import {
  ImagePlus,
  UploadCloud,
  Trash2,
  RefreshCw,
  CheckCircle2,
  AlertCircle,
  Loader2,
  FileImage,
  ShieldCheck,
  X,
} from "lucide-react";

type ImageUploadProps = {
  value: string;
  fileId?: string;
  folder?: string;
  onChange: (url: string, fileId: string) => void;
  onRemove: () => void;
};

type ImageKitAuth = {
  token: string;
  expire: number;
  signature: string;
  publicKey: string;
};

type ImageKitUploadResult = {
  url?: string;
  fileId?: string;
  name?: string;
  message?: string;
};

const MAX_FILE_SIZE = 10 * 1024 * 1024;

function normalizeFolder(folder: string): string {
  const parts = folder
    .split("/")
    .filter(Boolean);

  if (
    parts.length === 0 ||
    parts.some((part) => part === "." || part === "..")
  ) {
    throw new Error("Please provide a valid ImageKit folder.");
  }

  return `/${parts.join("/")}`;
}

function createUniqueFileName(file: File, folderPath: string): string {
  const folderName =
    folderPath.split("/").filter(Boolean).pop() || "image";

  const safePrefix = folderName
    .toLowerCase()
    .replace(/[^a-z0-9-]/g, "-");

  // Example: courses-20261024-8ab2d9....webp
  const date = new Date()
    .toISOString()
    .slice(0, 10)
    .replace(/-/g, "");

  const randomId =
    typeof crypto !== "undefined" &&
    typeof crypto.randomUUID === "function"
      ? crypto.randomUUID().replace(/-/g, "")
      : `${Date.now().toString(36)}${Math.random()
          .toString(36)
          .slice(2, 14)}`;

  const originalExtension = file.name.split(".").pop()?.toLowerCase();

  const extension =
    originalExtension && /^[a-z0-9]{1,8}$/.test(originalExtension)
      ? originalExtension
      : "img";

  return `${safePrefix}-${date}-${randomId}.${extension}`;
}

export default function ImageUpload({
  value,
  fileId,
  folder = "/courses",
  onChange,
  onRemove,
}: ImageUploadProps) {
  const inputRef = useRef<HTMLInputElement>(null);

  const [uploading, setUploading] = useState(false);
  const [error, setError] = useState("");
  const [dragging, setDragging] = useState(false);

  async function uploadFile(file: File) {
    setError("");

    if (!file.type.startsWith("image/")) {
      setError("Please select a valid image file.");
      return;
    }

    if (file.size > MAX_FILE_SIZE) {
      setError("Image size must be 10 MB or less.");
      return;
    }

    let folderPath: string;

    try {
      folderPath = normalizeFolder(folder);
    } catch (err) {
      setError(
        err instanceof Error
          ? err.message
          : "Invalid ImageKit folder.",
      );
      return;
    }

    setUploading(true);

    try {
      // Get temporary authentication generated by the server.
      const authResponse = await fetch("/api/upload-auth", {
        method: "GET",
        cache: "no-store",
      });

      const authData = await authResponse.json().catch(() => ({}));

      if (!authResponse.ok) {
        throw new Error(
          authData.message ||
            authData.error ||
            "Failed to authenticate the ImageKit upload.",
        );
      }

      const auth = authData as ImageKitAuth;

      if (
        !auth.token ||
        !auth.signature ||
        !auth.expire ||
        !auth.publicKey
      ) {
        throw new Error(
          "ImageKit returned incomplete authentication details.",
        );
      }

      const generatedFileName = createUniqueFileName(file, folderPath);

      const formData = new FormData();

      formData.append("file", file);

      // Use our generated name rather than the original file name.
      formData.append("fileName", generatedFileName);

      // Organize files under /courses, /services, or /user.
      formData.append("folder", folderPath);

      // The generated filename already contains a UUID.
      // Do not let ImageKit replace it with the original filename.
      formData.append("useUniqueFileName", "false");

      // Never overwrite an existing file if a collision occurs.
      formData.append("overwriteFile", "false");

      formData.append("token", auth.token);
      formData.append("expire", String(auth.expire));
      formData.append("signature", auth.signature);
      formData.append("publicKey", auth.publicKey);

      const uploadResponse = await fetch(
        "https://upload.imagekit.io/api/v1/files/upload",
        {
          method: "POST",
          body: formData,
        },
      );

      const uploadResult: ImageKitUploadResult =
        await uploadResponse.json().catch(() => ({}));

      if (!uploadResponse.ok) {
        throw new Error(
          uploadResult.message || "Image upload failed.",
        );
      }

      if (!uploadResult.url || !uploadResult.fileId) {
        throw new Error(
          "ImageKit did not return the image URL and file ID.",
        );
      }

      // Firestore will save these values when the parent form is saved.
      onChange(uploadResult.url, uploadResult.fileId);
      setError("");
    } catch (uploadError) {
      console.error("ImageKit upload failed:", uploadError);

      setError(
        uploadError instanceof Error
          ? uploadError.message
          : "Image upload failed.",
      );
    } finally {
      setUploading(false);

      if (inputRef.current) {
        inputRef.current.value = "";
      }
    }
  }

  async function handleFileChange(
    event: ChangeEvent<HTMLInputElement>,
  ) {
    const file = event.target.files?.[0];

    if (file) {
      await uploadFile(file);
    }
  }

  function handleDragOver(event: DragEvent<HTMLDivElement>) {
    event.preventDefault();

    if (!uploading) {
      setDragging(true);
    }
  }

  function handleDragLeave(event: DragEvent<HTMLDivElement>) {
    event.preventDefault();

    const nextTarget = event.relatedTarget;

    if (
      !(nextTarget instanceof Node) ||
      !event.currentTarget.contains(nextTarget)
    ) {
      setDragging(false);
    }
  }

  async function handleDrop(event: DragEvent<HTMLDivElement>) {
    event.preventDefault();
    setDragging(false);

    if (uploading) return;

    const file = event.dataTransfer.files?.[0];

    if (file) {
      await uploadFile(file);
    }
  }

  function openFilePicker() {
    if (!uploading) {
      inputRef.current?.click();
    }
  }

  function handleDropZoneKeyDown(
    event: KeyboardEvent<HTMLDivElement>,
  ) {
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      openFilePicker();
    }
  }

  function handleRemove() {
    setError("");
    onRemove();
  }

  const folderLabel = (() => {
    try {
      return normalizeFolder(folder);
    } catch {
      return folder;
    }
  })();

  return (
    <div
      className="w-full space-y-4"
      onDragOver={handleDragOver}
      onDragLeave={handleDragLeave}
      onDrop={handleDrop}
    >
      <div
        className={`overflow-hidden rounded-2xl border bg-white shadow-sm transition ${
          dragging
            ? "border-indigo-500 ring-4 ring-indigo-100"
            : "border-slate-200"
        }`}
      >
        <div className="flex items-center justify-between gap-3 border-b border-slate-100 px-4 py-4 sm:px-5">
          <div className="flex min-w-0 items-center gap-3">
            <div className="flex h-10 w-10 shrink-0 items-center justify-center rounded-xl bg-indigo-50 text-indigo-600">
              <ImagePlus size={20} />
            </div>

            <div className="min-w-0">
              <h3 className="text-sm font-semibold text-slate-900">
                Cover image
              </h3>
              <p className="mt-0.5 text-xs text-slate-500">
                Managed by ImageKit
              </p>
            </div>
          </div>

          {value && !uploading && (
            <span className="inline-flex shrink-0 items-center gap-1.5 rounded-full bg-emerald-50 px-2.5 py-1 text-xs font-medium text-emerald-700">
              <CheckCircle2 size={13} />
              Ready
            </span>
          )}
        </div>

        <div className="space-y-4 p-4 sm:p-5">
          {value ? (
            <>
              <div className="group relative overflow-hidden rounded-xl border border-slate-200 bg-slate-100">
                <div className="relative aspect-[16/9] max-h-80 w-full">
                  {/* eslint-disable-next-line @next/next/no-img-element */}
                  <img
                    src={value}
                    alt="Image preview"
                    className={`h-full w-full object-cover transition ${
                      uploading ? "opacity-40" : ""
                    }`}
                  />

                  {!uploading && (
                    <>
                      <div className="absolute inset-0 bg-gradient-to-t from-black/60 via-transparent to-black/20" />

                      <span className="absolute left-3 top-3 inline-flex items-center gap-1.5 rounded-full border border-white/20 bg-black/45 px-3 py-1.5 text-xs font-medium text-white backdrop-blur">
                        <FileImage size={13} />
                        Preview
                      </span>

                      <div className="absolute bottom-3 left-3 right-3 flex items-end justify-between gap-3">
                        <p className="text-sm font-medium text-white">
                          Current image
                        </p>

                        <button
                          type="button"
                          onClick={openFilePicker}
                          className="inline-flex shrink-0 items-center gap-2 rounded-lg bg-white px-3 py-2 text-xs font-semibold text-slate-800 transition hover:bg-slate-100"
                        >
                          <RefreshCw size={14} />
                          Replace
                        </button>
                      </div>
                    </>
                  )}

                  {uploading && (
                    <div className="absolute inset-0 flex flex-col items-center justify-center bg-white/75 backdrop-blur-sm">
                      <Loader2
                        size={30}
                        className="animate-spin text-indigo-600"
                      />
                      <p className="mt-3 text-sm font-semibold text-slate-800">
                        Uploading image...
                      </p>
                      <p className="mt-1 text-xs text-slate-500">
                        Please keep this page open.
                      </p>
                    </div>
                  )}
                </div>
              </div>

              <div className="flex flex-col gap-3 rounded-xl bg-slate-50 p-3 sm:flex-row sm:items-center sm:justify-between">
                <div className="flex min-w-0 items-start gap-2.5">
                  {fileId ? (
                    <ShieldCheck
                      size={17}
                      className="mt-0.5 shrink-0 text-emerald-600"
                    />
                  ) : (
                    <AlertCircle
                      size={17}
                      className="mt-0.5 shrink-0 text-amber-600"
                    />
                  )}

                  <div className="min-w-0">
                    <p className="text-xs font-medium text-slate-800">
                      {fileId
                        ? "ImageKit file ID linked"
                        : "ImageKit file ID unavailable"}
                    </p>

                    <p className="mt-1 break-all text-xs leading-5 text-slate-500">
                      {fileId || "The image file ID is missing."}
                    </p>

                    <p className="mt-1 text-xs text-slate-500">
                      Folder: {folderLabel}
                    </p>
                  </div>
                </div>

                <button
                  type="button"
                  onClick={handleRemove}
                  disabled={uploading}
                  className="inline-flex shrink-0 items-center justify-center gap-2 rounded-lg border border-red-200 bg-white px-3 py-2 text-xs font-semibold text-red-600 transition hover:bg-red-50 disabled:opacity-50"
                >
                  <Trash2 size={14} />
                  Remove image
                </button>
              </div>

              <p className="text-xs leading-5 text-slate-500">
                Save the course after removing or replacing the image
                to update Firestore and clean up the previous ImageKit file.
              </p>
            </>
          ) : (
            <div
              role="button"
              tabIndex={uploading ? -1 : 0}
              aria-label="Choose or drop an image"
              onClick={openFilePicker}
              onKeyDown={handleDropZoneKeyDown}
              className={`flex min-h-64 cursor-pointer flex-col items-center justify-center rounded-xl border-2 border-dashed px-5 py-8 text-center transition focus:outline-none focus:ring-4 focus:ring-indigo-100 ${
                dragging
                  ? "border-indigo-500 bg-indigo-50"
                  : "border-slate-200 bg-slate-50/70 hover:border-indigo-300 hover:bg-indigo-50/50"
              } ${uploading ? "pointer-events-none opacity-70" : ""}`}
            >
              <div className="flex h-16 w-16 items-center justify-center rounded-2xl bg-white text-indigo-600 shadow-sm ring-1 ring-slate-200">
                {uploading ? (
                  <Loader2 size={28} className="animate-spin" />
                ) : (
                  <UploadCloud size={29} strokeWidth={1.8} />
                )}
              </div>

              <h4 className="mt-5 text-sm font-semibold text-slate-900">
                {uploading
                  ? "Uploading your image..."
                  : dragging
                    ? "Drop your image here"
                    : "Choose an image"}
              </h4>

              <p className="mt-2 max-w-xs text-xs leading-5 text-slate-500">
                Drag and drop an image here, or click to browse your device.
              </p>

              {!uploading && (
                <span className="mt-5 inline-flex items-center gap-2 rounded-lg bg-indigo-600 px-4 py-2.5 text-sm font-semibold text-white shadow-sm transition hover:bg-indigo-700">
                  <ImagePlus size={16} />
                  Select image
                </span>
              )}

              <div className="mt-5 flex flex-wrap items-center justify-center gap-2 text-[11px] font-medium text-slate-400">
                <span>JPG</span>
                <span>·</span>
                <span>PNG</span>
                <span>·</span>
                <span>WEBP</span>
                <span>·</span>
                <span>Maximum 10 MB</span>
              </div>

              <p className="mt-3 text-xs font-medium text-indigo-600">
                Destination: {folderLabel}
              </p>
            </div>
          )}

          <input
            ref={inputRef}
            type="file"
            accept="image/*"
            onChange={handleFileChange}
            disabled={uploading}
            className="hidden"
            aria-label="Select an image"
          />

          {uploading && (
            <div
              role="status"
              className="flex items-center gap-3 rounded-xl border border-indigo-100 bg-indigo-50 p-3.5"
            >
              <Loader2
                size={18}
                className="shrink-0 animate-spin text-indigo-600"
              />
              <div>
                <p className="text-xs font-semibold text-indigo-900">
                  Uploading to ImageKit
                </p>
                <p className="mt-1 text-xs text-indigo-700">
                  Folder: {folderLabel}
                </p>
              </div>
            </div>
          )}

          {error && (
            <div
              role="alert"
              className="flex items-start gap-3 rounded-xl border border-red-200 bg-red-50 p-3.5"
            >
              <AlertCircle
                size={18}
                className="mt-0.5 shrink-0 text-red-600"
              />

              <div className="min-w-0 flex-1">
                <p className="text-sm font-semibold text-red-800">
                  Upload failed
                </p>
                <p className="mt-1 break-words text-xs leading-5 text-red-700">
                  {error}
                </p>
              </div>

              <button
                type="button"
                aria-label="Dismiss error"
                onClick={() => setError("")}
                className="shrink-0 rounded-md p-1 text-red-500 hover:bg-red-100"
              >
                <X size={15} />
              </button>
            </div>
          )}
        </div>

      </div>
    </div>
  );
}
